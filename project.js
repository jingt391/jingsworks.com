  /* =================================================
     GET URL PARAMETER
  ================================================= */
  
  const params =
    new URLSearchParams(
      window.location.search
    );
  
  
  const projectId =
    params.get("project");
  
  
  const project =
    projects[projectId];
  
  
  
  /* =================================================
     INVALID PROJECT
  ================================================= */
  
  if (!project) {
  
    window.location.href =
      "index.html#work";
  
  }
  
  
  
  /* =================================================
     LOAD PROJECT
  ================================================= */
  
  else {
  
  
    /* ===============================================
       PAGE TITLE
    =============================================== */
  
    document.title =
      `YUE JING — ${project.title}`;
  
  
  
    /* ===============================================
       TEXT
    =============================================== */
  
    const titleElement =
      document.getElementById(
        "project-title"
      );
  
  
    const categoryElement =
      document.getElementById(
        "project-category"
      );
  
  
    const yearElement =
      document.getElementById(
        "project-year"
      );
  
  
    const typeElement =
      document.getElementById(
        "project-type"
      );
  
  
    const descriptionElement =
      document.getElementById(
        "project-description"
      );
  
  
    if (titleElement) {
  
      titleElement.textContent =
        project.title;
  
    }
  
  
    if (categoryElement) {
  
      categoryElement.textContent =
        project.category;
  
    }
  
  
    if (yearElement) {
  
      yearElement.textContent =
        project.year;
  
    }
  
  
    if (typeElement) {
  
      typeElement.textContent =
        project.type;
  
    }
  
  
    if (descriptionElement) {
  
      descriptionElement.innerHTML =
        project.description;
  
    }
  
  
  
    /* ===============================================
       VISUALS
    =============================================== */
  
    const visualsContainer =
      document.getElementById(
        "project-visuals"
      );
  
  
    if (
      visualsContainer &&
      project.visuals
    ) {
  
      visualsContainer.innerHTML =
        "";
  
  
      project.visuals.forEach(
        (visual) => {
  
  
          const wrapper =
            document.createElement(
              "div"
            );
  
  
          wrapper.className =
            "project-visual";
  
  
          /* =========================================
             IMAGE
          ========================================= */
  
          if (
            visual.type ===
            "image"
          ) {
  
            const image =
              document.createElement(
                "img"
              );
  
  
            image.src =
              visual.src;
  
  
            image.alt =
              visual.alt ||
              project.title;
  
  
            image.loading =
              "eager";
  
  
            image.addEventListener(
              "error",
              () => {
  
                console.error(
                  "Image failed to load:",
                  visual.src
                );
  
              }
            );
  
  
            wrapper.appendChild(
              image
            );
  
          }
  
  
  
          /* =========================================
             VIDEO
          ========================================= */
  
          if (
            visual.type ===
            "video"
          ) {
  
            const video =
              document.createElement(
                "video"
              );
  
  
            video.autoplay =
              true;
  
  
            video.muted =
              true;
  
  
            video.loop =
              true;
  
  
            video.playsInline =
              true;
  
  
            video.controls =
              true;
  
  
            video.preload =
              "auto";
  
  
            video.setAttribute(
              "playsinline",
              ""
            );
  
  
            video.src =
              visual.src;
  
  
            /* ---------------------------------------
               VIDEO ERROR FALLBACK
            --------------------------------------- */
  
            video.addEventListener(
              "error",
              () => {
  
                console.warn(
                  "Video failed to load:",
                  visual.src
                );
  
  
                if (
                  visual.fallback &&
                  visual.fallback.length
                ) {
  
                  const fallback =
                    visual.fallback[0];
  
  
                  video.src =
                    fallback;
  
  
                  video.load();
  
                }
  
              }
            );
  
  
            wrapper.appendChild(
              video
            );
  
          }
  
  
          visualsContainer.appendChild(
            wrapper
          );
  
        }
      );
  
    }
  
  }